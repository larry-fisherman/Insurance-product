-- Local disposable infrastructure only. Runs once for a newly initialized volume.
\getenv migration_password CGL_POSTGRES_MIGRATION_PASSWORD

CREATE ROLE cgl_migrator WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE
    NOINHERIT NOREPLICATION NOBYPASSRLS PASSWORD :'migration_password';
CREATE ROLE cgl_runtime WITH NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE
    NOINHERIT NOREPLICATION NOBYPASSRLS;
CREATE ROLE cgl_auth WITH NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE
    NOINHERIT NOREPLICATION NOBYPASSRLS;

ALTER DATABASE cgl_dev OWNER TO cgl_migrator;
REVOKE ALL ON DATABASE cgl_dev FROM PUBLIC;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
